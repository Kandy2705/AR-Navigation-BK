#if UNITY_EDITOR
namespace Game.Foundation.UI.EditorTools
{
    /// <summary>
    /// Asset locations shared by the Canvas UI generators, import processor and tests.
    /// Layout follows the sun-studio reference project: one folder per screen under
    /// Bundles/UI/&lt;Name&gt;UI/{Prefabs,Arts}, shared pieces under Bundles/UI/Common.
    /// </summary>
    public static class UiCanvasPaths
    {
        public const string UiBundles = "Assets/Game/Bundles/UI";
        public const string CommonArts = UiBundles + "/Common/Arts";
        public const string CommonPrefabs = UiBundles + "/Common/Prefabs";
        public const string Fonts = "Assets/Game/Bundles/Fonts/Game";

        public const string RoundedSprite = CommonArts + "/ui_rounded_9slice.png";
        public const string CircleSprite = CommonArts + "/ui_circle.png";
        public const string AppCanvasPrefab = CommonPrefabs + "/AppCanvas.prefab";

        public const string ShellScene = "Assets/Game/Bundles/Scenes/AppShell.unity";

        /// <summary>Rendered page previews land here (Logs/ is git-ignored).</summary>
        public const string PreviewFolder = "Logs/UiPreview";

        public static string ScreenPrefab(string screenName)
        {
            return UiBundles + "/" + screenName + "/Prefabs/" + screenName + ".prefab";
        }

        public static string CommonArt(string fileName)
        {
            return CommonArts + "/" + fileName;
        }

        public static string ScreenArt(string screenName, string fileName)
        {
            return UiBundles + "/" + screenName + "/Arts/" + fileName;
        }

        /// <summary>Source TTFs imported by the legacy UI Toolkit screens.</summary>
        public const string PoppinsSourceFolder = "Assets/UI/Fonts";

        public const string TmpFallbackFont = "Assets/Plugins/TextMesh Pro/Resources/Fonts & Materials/LiberationSans SDF.asset";

        /// <summary>Our own Liberation fallback (covers the Vietnamese letters Poppins lacks), built with the standard SDF shader.</summary>
        public const string FallbackSourceTtf = "Assets/Plugins/TextMesh Pro/Fonts/LiberationSans.ttf";
        public const string FallbackFontAsset = Fonts + "/LiberationSans-Fallback SDF.asset";

        /// <summary>Used instead of TMP's Android default (Mobile/Distance Field), which draws a smeared foot under glyphs.</summary>
        public const string SdfShaderName = "TextMeshPro/Distance Field";

        public static readonly string[] PoppinsWeights = { "Light", "Regular", "Medium", "SemiBold", "Bold" };

        // Phase 2 shared sprites (generated by UiCanvasSpriteGenerator unless noted).
        public const string RoundedR16File = "ui_rounded_r16.png";
        public const string OutlineR16File = "ui_outline_r16.png";
        public const string CheckboxFillFile = "ui_checkbox_fill.png";
        public const string CheckboxOutlineFile = "ui_checkbox_outline.png";
        public const string BackIconFile = "ui_icon_back.png";

        // Phase 3 (register): avatar shape and dropdown chevron.
        public const string RoundedR32File = "ui_rounded_r32.png";
        public const string ChevronDownFile = "ui_icon_chevron_down.png";

        // Copied from the legacy UI Toolkit images (Assets/UI/Images) so the Canvas UI owns its icons.
        public const string UserIconFile = "icon_user.png";
        public const string PenBadgeFile = "icon_pen_badge.png";
        public const string EyeIconFile = "icon_eye.png";
        public const string EyeOffIconFile = "icon_eye_off.png";
        public const string MailIconFile = "icon_mail.png";
        public const string CheckCircleFile = "icon_check_circle.png";

        /// <summary>9-slice border (all sides) for the sprites that stretch; 0 means no border.</summary>
        public static int NineSliceBorder(string fileName)
        {
            switch (fileName)
            {
                case "ui_rounded_9slice.png": return RoundedCornerPixels;
                case RoundedR16File:
                case OutlineR16File: return 16;
                case RoundedR32File: return 32;
                case CheckboxFillFile:
                case CheckboxOutlineFile: return 8;
                default: return 0;
            }
        }

        public static string PoppinsFontAsset(string weight)
        {
            return Fonts + "/Poppins-" + weight + " SDF.asset";
        }

        /// <summary>True for textures that live in a screen's (or Common's) Arts folder.</summary>
        public static bool IsUiArt(string assetPath)
        {
            return assetPath.StartsWith(UiBundles + "/") && assetPath.Contains("/Arts/");
        }

        /// <summary>Corner size of <see cref="RoundedSprite"/>; also its 9-slice border.</summary>
        public const int RoundedCornerPixels = 24;
    }
}
#endif
